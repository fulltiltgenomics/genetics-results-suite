#!/usr/bin/env python3
"""Generate the sandbox image's on-demand documentation: sandbox/schema/*.md and
sandbox/stubs/*.pyi (genetics-results-suite-4h6.13).

WHY THESE FILES EXIST. The code-execution agent (epic genetics-results-suite-4h6) gets a
sandbox and an SDK, not 44 tool schemas. It has to learn the BigQuery views and the SDK's
signatures the way a developer does — by reading documentation when a question needs it —
because there is no spare prompt-cache breakpoint to front-load a schema block into
(genetics-mcp-server/docs/project-spec.md:420). The Dockerfile copies these two
directories verbatim to /genetics/schema (GENETICS_SCHEMA_DIR) and /genetics/sdk
(GENETICS_STUBS_DIR).

WHY IT GENERATES RATHER THAN TRANSCRIBES. Everything below is derived at run time from
configs/datasets.yaml (this repo's canonical copy) and from the SDK's own source. Not one
column name, table name, example query or correctness rule is written out in this file.
That is the whole design constraint, not a style choice:

  - CLAUDE.md: "A doc is stale the moment it *enumerates* something the code no longer
    matches. Counts and lists rot silently." A transcribed schema is exactly that, and
    inside a container image nothing would ever notice.
  - genetics-results-suite-5p5 is open and will rewrite credible_sets_v's variant/chr
    guidance the moment the clustering swap runs. A copy of that guidance baked into this
    script would then ship a rule the canonical file contradicts, and the image would
    still build green.

So the rule for anyone editing this file: to change what the schema docs SAY, edit
configs/datasets.yaml. To change how they are LAID OUT, edit this file. If a fact belongs
in the docs and has nowhere to live in datasets.yaml, add a field there (and update
docs/datasets-yaml-schema.md and docs/adding-datasets.md per CLAUDE.md's
documentation-ownership table) — do not hardcode it here.

The .pyi stubs are likewise read out of the SDK source with `ast`, never imported: the
generator runs on a build host that has no polars/httpx and no reason to grow them, and
importing the SDK would execute genetics_mcp_server.config.settings.

Usage:
    scripts/gen-sandbox-docs.py [--sdk-src DIR] [--check]

    --sdk-src   the staged genetics-mcp-server checkout (default sandbox/.sdk-src, which
                is what scripts/build.sh and scripts/build-all.sh create).
    --check     generate into memory and diff against what is on disk; exit 1 on any
                difference. This is what keeps the committed copies from rotting.

Exit 0 = written (or up to date under --check), 1 = out of date / a rule is missing,
2 = the generator could not run.
"""

import argparse
import ast
import os
import re
import sys
import textwrap

try:
    import yaml
except ImportError:
    print("cannot run: PyYAML is missing (pip install pyyaml)", file=sys.stderr)
    sys.exit(2)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATASETS_YAML = os.path.join(ROOT, "configs", "datasets.yaml")
SCHEMA_DIR = os.path.join(ROOT, "sandbox", "schema")
STUBS_DIR = os.path.join(ROOT, "sandbox", "stubs")
DEFAULT_SDK_SRC = os.path.join(ROOT, "sandbox", ".sdk-src")

BANNER = (
    "<!-- Generated by scripts/gen-sandbox-docs.py from configs/datasets.yaml.\n"
    "     Do not edit: edit configs/datasets.yaml and regenerate. -->"
)
STUB_BANNER = (
    "# Generated by scripts/gen-sandbox-docs.py from the genetics SDK source.\n"
    "# Do not edit: edit genetics-mcp-server/src/genetics_mcp_server/sdk/ and regenerate.\n"
    "# Signature reference only — this file is NOT on PYTHONPATH and is not importable.\n"
    "# The real package lives in /opt/venv; two copies of these names on the path would\n"
    "# shadow each other silently (genetics-results-suite-4h6.6)."
)


# --------------------------------------------------------------------------- helpers


def _unfold(text):
    """Collapse a YAML folded scalar back to one paragraph per blank line.

    `>-` already joined the wrapped source lines, but several descriptions are long
    enough that reading them as a single 900-character line is worse than reading
    wrapped prose, so re-wrap for a human (and a model) reading the file directly.
    """
    paragraphs = [" ".join(p.split()) for p in str(text).split("\n\n")]
    return "\n\n".join(textwrap.fill(p, 92) for p in paragraphs if p)


def _table_cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


# ----------------------------------------------------------------- schema markdown


def render_view(name, table):
    """One /genetics/schema/<view>.md, entirely out of tables.<view> in datasets.yaml.

    Every section is a field of that block: `description` (which is where the
    peak_to_gene join warning and the caQTL/gene rule live), `columns`,
    `categorical_columns`, and `examples` (which is where the chr-alongside-variant
    partition-pruning rule lives, on the example whose SQL it applies to). Nothing is
    filtered or summarised — a rule added to any of those fields reaches the image on
    the next build without touching this script.
    """
    out = [BANNER, "", f"# {name}", ""]
    out += [_unfold(table["description"]), ""]

    out += ["## Columns", "", "| column | description |", "| --- | --- |"]
    for col, desc in table["columns"].items():
        out.append(f"| `{col}` | {_table_cell(desc)} |")
    out.append("")

    categorical = table.get("categorical_columns") or {}
    if categorical:
        out += [
            "## Columns with a small, enumerable set of values",
            "",
            "`SELECT DISTINCT` these before filtering on them rather than guessing a value.",
            "A parent means the values are scoped by that column, so enumerate the pair.",
            "",
            "| column | scoped by |",
            "| --- | --- |",
        ]
        for col, parent in categorical.items():
            out.append(f"| `{col}` | {f'`{parent}`' if parent else '—'} |")
        out.append("")

    examples = table.get("examples") or []
    if examples:
        out += ["## Worked examples", ""]
        for example in examples:
            out += [f"### {' '.join(str(example['description']).split())}", ""]
            out += ["```sql", str(example["sql"]).rstrip(), "```", ""]

    return "\n".join(out).rstrip() + "\n"


def render_index(tables):
    """A single entry point so a script can see what exists without listing a directory
    it may not have been told about. First sentence only: the point of progressive
    disclosure is that the model opens the one file it needs."""
    out = [
        BANNER,
        "",
        "# BigQuery views",
        "",
        _unfold(
            "One file per view. Read the file for the view a question is about; the "
            "columns, the value conventions and worked example SQL are all there. Query "
            "them with genetics.sql(...) — see the SDK stubs in the directory named by "
            "GENETICS_STUBS_DIR."
            "\n\n"
            "Every view lives in the BigQuery dataset `genetics_results`. Qualify each one "
            "as `genetics_results.<view>`, the way the worked examples below are written: "
            "the query service sets no default dataset, and its fallback that patches an "
            "unqualified name is a regular expression that cannot tell a table position "
            "from a string literal."
            "\n\n"
            "Each query runs under three ceilings: 25,000 returned rows, 50 GB scanned per "
            "query, and 200 GB scanned across one execution. Exceeding any of them raises "
            "GeneticsError — a truncated answer is never returned as a short frame — so "
            "aggregate and filter in SQL rather than fetching every row, and add the "
            "partition predicate each view's file names."
        ),
        "",
        "| view | summary |",
        "| --- | --- |",
    ]
    for name, table in tables.items():
        first = " ".join(str(table["description"]).split()).split(". ")[0].rstrip(".")
        out.append(f"| [`{name}`]({name}.md) | {_table_cell(first)}. |")
    return "\n".join(out).rstrip() + "\n"


def render_schema_docs(datasets_yaml_path):
    with open(datasets_yaml_path) as fh:
        config = yaml.safe_load(fh)
    tables = config.get("tables") or {}
    if not tables:
        raise SystemExit(f"{datasets_yaml_path} has no `tables:` block")
    files = {f"{name}.md": render_view(name, table) for name, table in tables.items()}
    files["README.md"] = render_index(tables)
    return files


# ------------------------------------------------------------------------ pyi stubs


def _annotation(node):
    return ast.unparse(node) if node is not None else None


def _signature(func, drop_self=True):
    """Reconstruct a def's parameter list, keeping `/` and `*` markers and defaults.

    ast.unparse on the whole FunctionDef would also bring the body; only the header is
    wanted, and `self` is dropped for the module-level form because that is what a
    script actually calls.
    """
    args = func.args
    parts = []

    posonly = list(args.posonlyargs)
    normal = list(args.args)
    if drop_self:
        target = posonly if posonly else normal
        if target and target[0].arg in ("self", "cls"):
            del target[0]
    n_posonly = len(posonly)
    positional = posonly + normal
    defaults = list(args.defaults)
    pad = len(positional) - len(defaults)

    for i, arg in enumerate(positional):
        rendered = arg.arg
        annotation = _annotation(arg.annotation)
        if annotation:
            rendered += f": {annotation}"
        if i >= pad:
            default = ast.unparse(defaults[i - pad])
            rendered += f" = {default}" if annotation else f"={default}"
        parts.append(rendered)
        if n_posonly and i == n_posonly - 1:
            parts.append("/")

    if args.vararg:
        annotation = _annotation(args.vararg.annotation)
        parts.append(f"*{args.vararg.arg}" + (f": {annotation}" if annotation else ""))
    elif args.kwonlyargs:
        parts.append("*")

    for arg, default in zip(args.kwonlyargs, args.kw_defaults):
        rendered = arg.arg
        annotation = _annotation(arg.annotation)
        if annotation:
            rendered += f": {annotation}"
        if default is not None:
            rendered += (
                f" = {ast.unparse(default)}" if annotation else f"={ast.unparse(default)}"
            )
        parts.append(rendered)

    if args.kwarg:
        annotation = _annotation(args.kwarg.annotation)
        parts.append(f"**{args.kwarg.arg}" + (f": {annotation}" if annotation else ""))

    return parts


def _docstring(doc, indent):
    """Re-indent a docstring body to the stub's nesting. ast.get_docstring strips the
    original common indentation, so without this every continuation line lands in
    column 0 and a reader cannot see where one signature's prose ends."""
    body = "\n".join(
        (f"{indent}    {line}" if line.strip() else "") for line in doc.rstrip().splitlines()
    ).lstrip()
    return f'{indent}    """{body}\n{indent}    """'


def _render_def(func, *, indent="", drop_self=True, is_async=None, name=None):
    async_def = isinstance(func, ast.AsyncFunctionDef) if is_async is None else is_async
    keyword = "async def" if async_def else "def"
    returns = _annotation(func.returns)
    tail = f" -> {returns}:" if returns else ":"
    params = _signature(func, drop_self)

    header = f"{indent}{keyword} {name or func.name}({', '.join(params)}){tail}"
    if len(header) > 96 and params:
        # one keyword-only argument per line: these are the signatures a script author
        # scans for "which selector does this take", and a 400-character line hides them
        opener = f"{indent}{keyword} {name or func.name}("
        lines = [opener] + [f"{indent}    {p}," for p in params] + [f"{indent}){tail}"]
        header = "\n".join(lines)

    doc = ast.get_docstring(func, clean=True)
    body = [_docstring(doc, indent)] if doc else []
    return "\n".join([header, *body, f"{indent}    ..."])


def _module(path):
    with open(path) as fh:
        return ast.parse(fh.read(), filename=path)


def _module_assignments(tree):
    return {
        node.targets[0].id: node.value
        for node in tree.body
        if isinstance(node, ast.Assign)
        and len(node.targets) == 1
        and isinstance(node.targets[0], ast.Name)
    }


def _literal(value, package_root):
    """Resolve a module-level constant to the literal behind it.

    A default rendered as a bare name (`limit: int = SOME_CONSTANT`) is unusable in a stub
    unless the name is defined there too, and writing the number into this script would be
    the transcription the whole design forbids. A constant that points at another module's
    class attribute is followed to that assignment in the package source.
    """
    if isinstance(value, ast.Constant):
        return value.value
    if not (isinstance(value, ast.Attribute) and isinstance(value.value, ast.Name)):
        return None
    owner, attr = value.value.id, value.attr
    for dirpath, _dirs, filenames in os.walk(package_root):
        for filename in sorted(filenames):
            if not filename.endswith(".py"):
                continue
            for node in ast.walk(_module(os.path.join(dirpath, filename))):
                if not (isinstance(node, ast.ClassDef) and node.name == owner):
                    continue
                for stmt in node.body:
                    if (
                        isinstance(stmt, ast.Assign)
                        and len(stmt.targets) == 1
                        and isinstance(stmt.targets[0], ast.Name)
                        and stmt.targets[0].id == attr
                        and isinstance(stmt.value, ast.Constant)
                    ):
                        return stmt.value.value
    return None


def _render_constants(text, assignments, package_root):
    """Every upper-case module constant of client.py that `text` actually mentions.

    Emitted so the stub is self-contained: a signature whose default is a name the reader
    cannot look up is worse than no default at all.
    """
    lines = []
    for name, value in assignments.items():
        if not name.isupper() or not re.search(rf"= {re.escape(name)}\b", text):
            continue
        resolved = _literal(value, package_root)
        if resolved is None:
            raise SystemExit(
                f"a stub signature defaults to {name}, whose value could not be resolved "
                "from the SDK source; the stub would document a name that does not exist"
            )
        lines.append(f"{name}: {type(resolved).__name__} = {resolved!r}")
    return lines


def _defs(tree):
    return {
        node.name: node
        for node in tree.body
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
    }


def _exported_functions(init_tree):
    """The public function list is `_FUNCTIONS` in sdk/__init__.py — the same tuple the
    package iterates to build its sync wrappers, so the stub cannot list a name the SDK
    does not export or miss one it does."""
    for node in init_tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "_FUNCTIONS" for t in node.targets
        ):
            return [ast.literal_eval(e) for e in node.value.elts]
    raise SystemExit("sdk/__init__.py has no _FUNCTIONS tuple to read the surface from")


def render_stubs(sdk_dir):
    init_tree = _module(os.path.join(sdk_dir, "__init__.py"))
    client_tree = _module(os.path.join(sdk_dir, "client.py"))
    errors_tree = _module(os.path.join(sdk_dir, "errors.py"))

    client_class = next(
        node
        for node in client_tree.body
        if isinstance(node, ast.ClassDef) and node.name == "GeneticsClient"
    )
    methods = {
        node.name: node
        for node in client_class.body
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
    }

    exported = _exported_functions(init_tree)
    missing = [name for name in exported if name not in methods]
    if missing:
        raise SystemExit(f"exported by sdk/__init__.py but absent from GeneticsClient: {missing}")

    files = {}
    package_root = os.path.dirname(sdk_dir)
    client_constants = _module_assignments(client_tree)

    # genetics.pyi — the surface a script actually calls, as sync functions.
    header = [STUB_BANNER, ""]
    module_doc = ast.get_docstring(init_tree, clean=True)
    if module_doc:
        header += [f'"""{module_doc.rstrip()}\n"""', ""]
    header += ["import polars as pl", "from typing import Any", ""]
    header += [
        "from genetics_mcp_server.sdk.client import GeneticsClient",
        "from genetics_mcp_server.sdk.errors import GeneticsError, GeneticsUsageError",
        "",
    ]
    body = []
    for name in exported:
        body += [_render_def(methods[name], is_async=False), ""]
    init_defs = _defs(init_tree)
    for name in ("configure", "get_client", "close"):
        if name in init_defs:
            body += [_render_def(init_defs[name], drop_self=False), ""]
    if "parse_region" in _defs(client_tree):
        body += [_render_def(_defs(client_tree)["parse_region"], drop_self=False), ""]
    constants = _render_constants("\n".join(body), client_constants, package_root)
    lines = header + (constants + [""] if constants else []) + body
    files["genetics.pyi"] = "\n".join(lines).rstrip() + "\n"

    # client.pyi — the awaitable form, for a script that already has an event loop.
    header = [
        STUB_BANNER,
        "",
        "import polars as pl",
        "from typing import Any",
        "",
        "from genetics_mcp_server.tools.executor import ToolExecutor",
        "",
    ]
    body = []
    class_doc = ast.get_docstring(client_class, clean=True)
    body.append("class GeneticsClient:")
    if class_doc:
        body.append(_docstring(class_doc, ""))
    body.append("")
    for name, node in methods.items():
        if name.startswith("_") and name != "__init__":
            continue
        body += [_render_def(node, indent="    ", drop_self=False), ""]
    constants = _render_constants("\n".join(body), client_constants, package_root)
    lines = header + (constants + [""] if constants else []) + body
    files["client.pyi"] = "\n".join(lines).rstrip() + "\n"

    # errors.pyi — what a script catches.
    lines = [STUB_BANNER, ""]
    errors_doc = ast.get_docstring(errors_tree, clean=True)
    if errors_doc:
        lines += [f'"""{errors_doc.rstrip()}\n"""', ""]
    for node in errors_tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        bases = ", ".join(ast.unparse(b) for b in node.bases)
        lines.append(f"class {node.name}({bases}):" if bases else f"class {node.name}:")
        doc = ast.get_docstring(node, clean=True)
        if doc:
            lines.append(_docstring(doc, ""))
        lines += ["    ...", ""]
    files["errors.pyi"] = "\n".join(lines).rstrip() + "\n"

    return files


# ------------------------------------------------------------------------ file sync


def _sync(directory, files, suffixes, check):
    """Write `files` into `directory` and remove anything with a generated suffix that is
    no longer produced — a dropped view must lose its file, or the image documents a view
    that is not there. PLACEHOLDER files (genetics-results-suite-4h6.6) are swept by the
    same rule."""
    stale = []
    if os.path.isdir(directory):
        for existing in sorted(os.listdir(directory)):
            if existing.endswith(suffixes) and existing not in files:
                stale.append(existing)

    changed = []
    for name, content in sorted(files.items()):
        path = os.path.join(directory, name)
        current = None
        if os.path.exists(path):
            with open(path) as fh:
                current = fh.read()
        if current != content:
            changed.append(name)
            if not check:
                os.makedirs(directory, exist_ok=True)
                with open(path, "w") as fh:
                    fh.write(content)

    if not check:
        for name in stale:
            os.remove(os.path.join(directory, name))

    return changed, stale


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sdk-src", default=DEFAULT_SDK_SRC)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    sdk_dir = os.path.join(args.sdk_src, "src", "genetics_mcp_server", "sdk")
    if not os.path.isdir(sdk_dir):
        # same failure the build scripts already raise for a branch without the SDK: the
        # stubs cannot be invented, so refuse rather than ship a schema-only image
        print(
            f"cannot run: no genetics SDK at {sdk_dir}.\n"
            "Stage a genetics-mcp-server checkout there (scripts/build.sh and "
            "scripts/build-all.sh do this) or pass --sdk-src.",
            file=sys.stderr,
        )
        return 2

    schema_files = render_schema_docs(DATASETS_YAML)
    stub_files = render_stubs(sdk_dir)

    schema_changed, schema_stale = _sync(SCHEMA_DIR, schema_files, (".md",), args.check)
    stub_changed, stub_stale = _sync(STUBS_DIR, stub_files, (".pyi",), args.check)

    if args.check:
        drift = schema_changed + schema_stale + stub_changed + stub_stale
        if drift:
            print(
                "sandbox docs are out of date with configs/datasets.yaml or the SDK: "
                + ", ".join(sorted(drift)),
                file=sys.stderr,
            )
            print("run: scripts/gen-sandbox-docs.py", file=sys.stderr)
            return 1
        print(
            f"sandbox docs up to date ({len(schema_files)} schema files, "
            f"{len(stub_files)} stubs)"
        )
        return 0

    print(
        f"sandbox docs: {len(schema_files)} schema files "
        f"({len(schema_changed)} written), {len(stub_files)} stubs "
        f"({len(stub_changed)} written)"
        + (f", removed {len(schema_stale) + len(stub_stale)} stale" if schema_stale or stub_stale else "")
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
